# =============================================================================
# setup-host.sh — detect a host's hardware, configure, build, and start the
#                  llm-companion stack on it
#
# Usage:
#   ./setup-host.sh                    # local self-provisioning (localhost)
#   ./setup-host.sh <inventory-name>   # a host already in ansible/inventory/hosts.yml
#   ./setup-host.sh --ansible-user <user>   # local mode only: passed through
#                                              as -e ansible_user=<user>
#
# Writes ansible/inventory/host_vars/<hostname>.yml with the detected
# ollama_build_target, runs the Ansible playbook, then starts the
# llm-companion systemd service (Ansible's llm_stack role only *enables* it —
# see the comment on that task for why).
# =============================================================================

set -euo pipefail

GREEN='\033[0;32m'; CYAN='\033[0;36m'; RED='\033[0;31m'; NC='\033[0m'
info() { echo -e "${GREEN}[INFO]${NC}  $*"; }
step() { echo -e "${CYAN}[STEP]${NC}  $*"; }
die()  { echo -e "${RED}[ERR]${NC}   $*" >&2; exit 1; }

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" &>/dev/null && pwd)"
PROJECT_DIR="$(dirname -- "${SCRIPT_DIR}")"
HOSTS_FILE="${PROJECT_DIR}/ansible/inventory/hosts.yml"
HOST_VARS_DIR="${PROJECT_DIR}/ansible/inventory/host_vars"

ANSIBLE_USER=""
INVENTORY_NAME=""

# shellcheck disable=SC2034
while [[ $# -gt 0 ]]; do
    case "$1" in
        --ansible-user) [[ $# -ge 2 ]] || die "--ansible-user requires a value"
                         ANSIBLE_USER="$2"; shift 2 ;;
        -*) die "Unknown argument: $1" ;;
        *)  [[ -z "${INVENTORY_NAME}" ]] || die "Only one inventory hostname may be given (got a second: $1)"
            INVENTORY_NAME="$1"; shift ;;
    esac
done

# ── Resolve mode: local vs remote ─────────────────────────────────────────────
if [[ -z "${INVENTORY_NAME}" ]]; then
    MODE="local"
    HOSTNAME_FOR_VARS="localhost"
    info "Mode: local self-provisioning"
else
    MODE="remote"
    HOSTNAME_FOR_VARS="${INVENTORY_NAME}"
    [[ -f "${HOSTS_FILE}" ]] || die "No inventory file at ${HOSTS_FILE}.\n  Copy ansible/inventory/hosts.yml.example to hosts.yml and fill in your host first."

    step "Resolving connection info for '${INVENTORY_NAME}' from ${HOSTS_FILE}..."
    INVENTORY_JSON=$(ansible-inventory -i "${HOSTS_FILE}" --host "${INVENTORY_NAME}" 2>/dev/null) \
        || die "Host '${INVENTORY_NAME}' not found in ${HOSTS_FILE}.\n  Check the hostname matches an entry under 'hosts:' in that file."

    SSH_HOST=$(python3 -c "import json,sys; print(json.loads(sys.argv[1]).get('ansible_host',''))" "${INVENTORY_JSON}")
    SSH_USER=$(python3 -c "import json,sys; print(json.loads(sys.argv[1]).get('ansible_user',''))" "${INVENTORY_JSON}")
    SSH_KEY=$(python3 -c "import json,sys; print(json.loads(sys.argv[1]).get('ansible_ssh_private_key_file',''))" "${INVENTORY_JSON}")

    [[ -n "${SSH_HOST}" ]] || die "No ansible_host set for '${INVENTORY_NAME}' in ${HOSTS_FILE}"

    SSH_ARGS=(-o BatchMode=yes -o ConnectTimeout=10)
    [[ -n "${SSH_USER}" ]] && SSH_ARGS+=(-l "${SSH_USER}")
    [[ -n "${SSH_KEY}" ]] && SSH_ARGS+=(-i "${SSH_KEY/#\~/$HOME}")

    info "Target: ${SSH_USER:+${SSH_USER}@}${SSH_HOST}"
fi

# ── Hardware detection ────────────────────────────────────────────────────────
step "Detecting hardware..."
if [[ "${MODE}" == "local" ]]; then
    DETECT_OUTPUT=$("${SCRIPT_DIR}/detect-hardware.sh") \
        || die "Hardware detection failed. See the message above."
else
    DETECT_OUTPUT=$(ssh "${SSH_ARGS[@]}" "${SSH_HOST}" 'bash -s' < "${SCRIPT_DIR}/detect-hardware.sh") \
        || die "Hardware detection failed on ${SSH_HOST}. See the message above, or check SSH connectivity with:\n  ssh ${SSH_ARGS[*]} ${SSH_HOST} true"
fi

eval "${DETECT_OUTPUT}"
info "Architecture : ${ARCH}"
info "CPU cores    : ${CPU_COUNT}"
info "RAM          : ${RAM_GB} GB"
info "Accelerator  : ${ACCEL} (${VRAM_GB} GB VRAM)"
info "Build target : ${OLLAMA_BUILD_TARGET}"

# ── Write host_vars ───────────────────────────────────────────────────────────
mkdir -p "${HOST_VARS_DIR}"
HOST_VARS_FILE="${HOST_VARS_DIR}/${HOSTNAME_FOR_VARS}.yml"
step "Writing ${HOST_VARS_FILE}..."
cat > "${HOST_VARS_FILE}" << EOF
# SPDX-FileCopyrightText: 2026 Thomas Perrot <thomas.perrot@tupi.fr>
# SPDX-License-Identifier: GPL-3.0-only
# Auto-generated by setup-host.sh on $(date -u '+%Y-%m-%d') — safe to
# regenerate by re-running setup-host.sh; do not hand-edit.
---
ollama_build_target: ${OLLAMA_BUILD_TARGET}
EOF
info "Wrote ${HOST_VARS_FILE}"

# ── Run the Ansible playbook ──────────────────────────────────────────────────
step "Running Ansible playbook..."
if [[ "${MODE}" == "local" ]]; then
    ANSIBLE_ARGS=(-c local -i "localhost," "${PROJECT_DIR}/ansible/site.yml")
    [[ -n "${ANSIBLE_USER}" ]] && ANSIBLE_ARGS+=(-e "ansible_user=${ANSIBLE_USER}")
    ansible-playbook "${ANSIBLE_ARGS[@]}"
else
    ansible-playbook -i "${HOSTS_FILE}" --limit "${INVENTORY_NAME}" "${PROJECT_DIR}/ansible/site.yml"
fi
info "Ansible playbook complete"

# ── Start the service ─────────────────────────────────────────────────────────
# The llm_stack role only *enables* the systemd service (it relies on a
# cloud-init reboot to start cleanly in the VM flow — see that task's
# comment). A bare-metal host has no pending reboot, so start it explicitly.
step "Starting llm-companion service..."
if [[ "${MODE}" == "local" ]]; then
    systemctl --user start llm-companion
else
    ssh "${SSH_ARGS[@]}" "${SSH_HOST}" systemctl --user start llm-companion
fi
info "llm-companion service started"

echo ""
info "Done. Next step: ./scripts/pull-models.sh to pull models sized for this hardware."
